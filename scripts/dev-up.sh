#!/usr/bin/env bash
# Canonical: start local dev environment (postgres + cloud in Compose),
# wait for readiness, run explicit migrations.
# Mirrors production (both services in OCI) while keeping `go run` available
# for fast iteration (see README).
#
# On an empty database it also creates a development OWNER with a generated
# password and one device, so a fresh environment is usable in one step.
# The generated credentials are printed and saved to .dev-credentials
# (gitignored, mode 0600). DEVELOPMENT ONLY.
set -euo pipefail
source "$(dirname "$0")/lib.sh"

usage() {
  cat <<'EOF'
usage: ./scripts/dev-up.sh [options]

  --reset            DESTROY the local dev database first (development only)
  --device NAME      also create a device named NAME (repeatable)
  --no-setup         only start the stack; create no account or device
  --owner-login L    login for a newly created OWNER (default dev@example.test)
  --owner-name N     display name for a newly created OWNER (default "Dev Owner")
  -h, --help         show this help

On an empty database the OWNER and one device named "shop-dev" are created
automatically; on an existing database nothing is created unless --device
is given.
EOF
}

reset=false
setup=true
owner_login="${DEV_OWNER_LOGIN:-dev@example.test}"
owner_name="${DEV_OWNER_NAME:-Dev Owner}"
devices=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --reset) reset=true ;;
    --no-setup) setup=false ;;
    --device) devices+=("${2:?--device needs a name}"); shift ;;
    --owner-login) owner_login="${2:?--owner-login needs a value}"; shift ;;
    --owner-name) owner_name="${2:?--owner-name needs a value}"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

load_env
ensure_dev_reporting_env
ensure_dev_auth_env

export ENVIRONMENT="${ENVIRONMENT:-development}"
export DATABASE_URL="${DATABASE_URL:-postgres://test:test@localhost:5432/moonlight_dev?sslmode=disable}"

if $reset; then
  "$(dirname "$0")/dev-reset.sh"
fi

$(compose_cmd) -f "$COMPOSE_FILE" up --build -d

echo "waiting for postgres..."
wait_db_ready "$DATABASE_URL"

echo "running migrations..."
"$(dirname "$0")/migrate.sh" up

echo "waiting for cloud readiness..."
ready=false
for _ in $(seq 1 60); do
  if curl -fsS http://localhost:8080/health/ready >/dev/null 2>&1; then
    ready=true
    break
  fi
  sleep 1
done
if ! $ready; then
  echo "cloud did not become ready" >&2
  exit 1
fi
echo "MoonLightCloud ready at http://localhost:8080"

if ! $setup; then
  exit 0
fi

# Account and device setup talks to the local dev database only.
require_local_dev_db

work="$(mktemp -d "${TMPDIR:-/tmp}/moonlight-dev-up.XXXXXXXX")"
trap 'rm -rf -- "$work"' EXIT
(cd "$REPO_ROOT" && go build -o "$work/moonlight-cloud" ./cmd/moonlight-cloud)
cli="$work/moonlight-cloud"

credentials="$REPO_ROOT/.dev-credentials"
record() {
  umask 077
  printf '%s\n' "$@" >>"$credentials"
  chmod 600 "$credentials"
}

# A fresh OWNER only exists on an empty database; bootstrap refuses once one
# is present, which is how an existing environment is recognised.
password="$(head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 20)"
if output="$(printf '%s\n' "$password" | "$cli" auth bootstrap-owner --login "$owner_login" --display-name "$owner_name" --password-stdin 2>&1)"; then
  : >"$credentials"
  record "# MoonLightCloud development credentials ($(date -u +%Y-%m-%dT%H:%M:%SZ))" \
    "# Local development only. Regenerated by ./scripts/dev-up.sh --reset." \
    "" \
    "DASHBOARD_URL=http://localhost:8080/dashboard" \
    "OWNER_LOGIN=$owner_login" \
    "OWNER_PASSWORD=$password"
  echo
  echo "Created development OWNER:"
  echo "  dashboard: http://localhost:8080/dashboard"
  echo "  login:     $owner_login"
  echo "  password:  $password"
  echo "  First sign-in asks you to scan an MFA QR code."
  if [[ ${#devices[@]} -eq 0 ]]; then
    devices=("shop-dev")
  fi
elif [[ "$output" == *"already been bootstrapped"* ]]; then
  echo
  echo "An OWNER already exists; no account created (see .dev-credentials, or use --reset)."
else
  echo "$output" >&2
  exit 1
fi
unset password

for name in "${devices[@]}"; do
  created="$("$cli" device create --name "$name")"
  device_id="$(awk '/^Device ID:/{getline; print; exit}' <<<"$created")"
  credential="$(awk '/^Credential:/{getline; print; exit}' <<<"$created")"
  if [[ -z "$device_id" || -z "$credential" ]]; then
    echo "device creation for '$name' returned no credential" >&2
    exit 1
  fi
  record "" "DEVICE_NAME=$name" "DEVICE_ID=$device_id" "DEVICE_CREDENTIAL=$credential"
  echo
  echo "Created device '$name':"
  echo "  device id:  $device_id"
  echo "  credential: $credential"
  echo "  In MoonLightRetail: Settings → Sync → Device credential."
done

if [[ -f "$credentials" ]]; then
  echo
  echo "Saved to .dev-credentials (gitignored, owner-only)."
fi
